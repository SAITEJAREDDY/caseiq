def category_key_by_name(cat_id_to_name):
    """cat_id_to_name: {IC01: 'Identity / Authentication', ...} from load_phase1.
    Returns {category_id: category_key}, relying on Phase 1's IC01..IC18 order
    matching ISSUE_CATEGORY_KEYS (asserted in build())."""
    ids_in_order = sorted(cat_id_to_name, key=lambda cid: int(cid[2:]))
    return dict(zip(ids_in_order, ISSUE_CATEGORY_KEYS))


def component_flavors(component_id, component_category_weights, top_n=2):
    """Returns up to top_n category_ids a component is most associated with,
    by descending inferred weight (from issue_subcategory_components.csv)."""
    weights = component_category_weights.get(component_id, {})
    if not weights:
        return []
    ranked = sorted(weights.items(), key=lambda kv: -kv[1])
    return [cat_id for cat_id, _ in ranked[:top_n]]


