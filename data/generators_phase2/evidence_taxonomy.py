"""
Phase 2 evidence ontology for CaseIQ: signal catalog, metric catalog, the
root-cause -> evidence-pattern table, component-dependency inference rules,
and incident-eligibility weights.

Static, hand-authored reference data only — no LLM calls happen here, mirroring
data/generators/taxonomy.py's role in Phase 1. This file is intentionally
self-contained (it does not import data/generators/taxonomy.py) so Phase 2 has
zero coupling to Phase 1's generation code, only to Phase 1's *output CSVs*
(read via load_phase1.py). The 18 issue-category keys below are copied from
Phase 1's ontology because they are the join key into
component_category_weights (derived from issue_subcategory_components.csv) —
not because this module re-runs any Phase 1 logic.

Design principle (see the Phase 2 plan): every piece of case evidence is
generated by first looking up the case's existing gt_root_cause_id here, then
sampling from the pattern it points to — never invented independently and
reconciled after the fact.
"""

