"""
Phase 2 per-case evidence: case_telemetry, case_signals, configuration_snapshots,
plus the final assembly of phase2_observable.csv / phase2_ground_truth.csv.

Every case's evidence is generated by first looking up its existing
gt_root_cause_id in evidence_taxonomy.ROOT_CAUSE_EVIDENCE_PATTERNS, then
sampling metrics/signals from the pattern it points to (never invented
independently of the Phase 1 ground truth).
"""
from datetime import timedelta

import evidence_taxonomy as et

_EXTERNAL_FLAVORED_ROOT_CAUSES = {
    "third-party service failure", "identity provider outage",
    "expired API key", "dependency failure",
}

_CONFIG_KEYS = [
    "feature_flag.enabled", "rate_limit.requests_per_minute", "session.timeout_seconds",
    "retry.max_attempts", "tls.min_version", "connection_pool.max_size",
    "cache.ttl_seconds", "webhook.retry_backoff_ms", "auth.token_ttl_seconds",
    "region.failover_enabled", "autoscale.max_replicas", "queue.visibility_timeout_seconds",
]


def _sample_config_value(rng, key):
    if key in ("feature_flag.enabled", "region.failover_enabled"):
        return rng.choice(["true", "false"])
    if key == "tls.min_version":
        return rng.choice(["1.0", "1.1", "1.2", "1.3"])
    return str(rng.choice([5, 10, 30, 60, 100, 250, 500, 1000]))


def _dependency_target(rng, component_id, component_dependencies_by_component):
    edges = component_dependencies_by_component.get(component_id, [])
    if not edges:
        return component_id
    weights = [e["weight"] for e in edges]
    return rng.choices(edges, weights=weights)[0]["depends_on_component_id"]


def _telemetry_density(rng, richness, difficulty):
    if richness == "low":
        probs = [("none", 0.60), ("sparse", 0.30), ("dense", 0.10)]
    elif difficulty == "vague":
        probs = [("none", 0.25), ("sparse", 0.40), ("dense", 0.35)]
    else:
        probs = [("none", 0.15), ("sparse", 0.30), ("dense", 0.55)]
    return rng.choices([p[0] for p in probs], weights=[p[1] for p in probs])[0]


def build_evidence(rng, cases, d, component_flavor_map, component_dependencies, changes_result):
    component_id_to_name = d["component_id_to_name"]
    root_cause_id_to_name = d["root_cause_id_to_name"]

    dependencies_by_component = {}
    for e in component_dependencies:
        dependencies_by_component.setdefault(e["component_id"], []).append(e)
    cat_id_to_key = et.category_key_by_name(d["cat_id_to_name"])

    case_telemetry, case_signals, configuration_snapshots = [], [], []
    per_case_evidence = {}
    sig_rid, cfg_rid = 0, 0

    for case in cases:
        rc_name = root_cause_id_to_name[case["gt_root_cause_id"]]
        pattern = et.ROOT_CAUSE_EVIDENCE_PATTERNS[rc_name]
        created = case["created_date"]

        target_component = case["gt_component_id"]
        if pattern["dependency_flavored"]:
            target_component = _dependency_target(rng, case["gt_component_id"], dependencies_by_component)
        target_name = component_id_to_name.get(target_component, target_component)

        # ── Telemetry ──────────────────────────────────────────────────────────
        density = _telemetry_density(rng, pattern["evidence_richness"], case["gt_difficulty_archetype"])
        telemetry_rows, has_clear_anomaly = [], False
        if density != "none":
            anomalous_pool = pattern["anomalous_metrics"] or et.METRICS_BY_CATEGORY.get(case["gt_issue_category_id"], [])
            window_hours = 4
            window_end = created
            window_start = created - timedelta(hours=window_hours)
            if density == "dense":
                n_readings = 7
                metrics_to_plant = anomalous_pool[:1] or []
                healthy_candidates = [m["code"] for m in et.METRIC_CATALOG if m["code"] not in metrics_to_plant]
                extra = rng.sample(healthy_candidates, k=1) if healthy_candidates else []
                metrics = [(m, True) for m in metrics_to_plant] + [(m, False) for m in extra]
            else:  # sparse
                n_readings = 5
                metrics_to_plant = anomalous_pool[:1] or []
                metrics = [(m, True) for m in metrics_to_plant]

            anomaly_start_frac = rng.uniform(0.35, 0.85)
            for metric_code, is_target_anomalous in metrics:
                meta = et.METRIC_BY_CODE[metric_code]
                lo, hi = meta["normal"]
                span = (hi - lo) or 1
                for i in range(n_readings):
                    frac = i / max(n_readings - 1, 1)
                    ts = window_start + (window_end - window_start) * frac
                    anomalous_now = is_target_anomalous and frac >= anomaly_start_frac
                    if anomalous_now:
                        severity_mult = 1 + (frac - anomaly_start_frac) / max(1 - anomaly_start_frac, 0.01)
                        if meta["anomaly_dir"] == "up":
                            value = hi + span * 0.6 * severity_mult + rng.uniform(0, span * 0.1)
                        else:
                            value = max(0.0, lo - span * 0.4 * severity_mult)
                        has_clear_anomaly = True
                    else:
                        value = lo + rng.uniform(0, span)
                    telemetry_rows.append({
                        "case_id": case["id"], "component_id": target_component,
                        "metric_code": metric_code, "timestamp": ts.strftime("%Y-%m-%d %H:%M:%S"),
                        "value": round(value, 3), "is_anomalous": "true" if anomalous_now else "false",
                    })
        case_telemetry.extend(telemetry_rows)

        # ── Signals ────────────────────────────────────────────────────────────
        causal_signal_ids, distractor_signal_ids = [], []
        if pattern["evidence_richness"] != "low":
            n_causal = rng.choices([0, 1, 2, 3, 4], weights=[10, 25, 30, 25, 10])[0] if pattern["signal_pool"] else 0
            # Causal signals may repeat a code (e.g. two separate HTTP_403 events at
            # different times), since a real recurring symptom often fires more than once.
            causal_codes = [rng.choice(pattern["signal_pool"]) for _ in range(n_causal)] if pattern["signal_pool"] else []
        else:
            causal_codes = []
        n_distractor = rng.choices([0, 1, 2, 3, 4, 5, 6], weights=[5, 15, 20, 20, 20, 10, 10])[0]
        case_category_key = cat_id_to_key.get(case["gt_issue_category_id"], "UNKNOWN")
        other_categories = [c for c in et.ISSUE_CATEGORY_KEYS if c != case_category_key]
        distractor_pool = []
        for cat in rng.sample(other_categories, k=min(3, len(other_categories))):
            distractor_pool += et.SIGNALS_BY_CATEGORY.get(cat, [])
        distractor_codes = rng.sample(distractor_pool, k=min(n_distractor, len(distractor_pool))) if distractor_pool else []

        for code in causal_codes:
            sig_rid += 1
            offset_min = rng.randint(5, 90)
            ts = created - timedelta(minutes=offset_min)
            sig_id = f"SG{sig_rid:07d}"
            causal_signal_ids.append(sig_id)
            case_signals.append({
                "id": sig_id, "case_id": case["id"], "component_id": target_component,
                "signal_code": code, "timestamp": ts.strftime("%Y-%m-%d %H:%M:%S"),
                "message": et.SIGNAL_BY_CODE[code]["text"].format(component=target_name),
            })
        for code in distractor_codes:
            sig_rid += 1
            offset_min = rng.randint(0, 240)
            ts = created - timedelta(minutes=offset_min)
            other_comp = rng.choice(d["components"])
            sig_id = f"SG{sig_rid:07d}"
            distractor_signal_ids.append(sig_id)
            case_signals.append({
                "id": sig_id, "case_id": case["id"], "component_id": other_comp["id"],
                "signal_code": code, "timestamp": ts.strftime("%Y-%m-%d %H:%M:%S"),
                "message": et.SIGNAL_BY_CODE[code]["text"].format(component=other_comp["name"]),
            })

        # ── Configuration snapshots ───────────────────────────────────────────
        n_cfg = 0
        if rng.random() < 0.70:
            n_cfg = 2 if rng.random() < 0.20 else 1
        for _ in range(n_cfg):
            cfg_rid += 1
            key = rng.choice(_CONFIG_KEYS)
            snap_at = created + timedelta(hours=rng.uniform(0.1, 6))
            configuration_snapshots.append({
                "id": f"CFG{cfg_rid:06d}", "case_id": case["id"], "component_id": target_component,
                "snapshot_at": snap_at.strftime("%Y-%m-%d %H:%M:%S"), "config_key": key,
                "config_value": _sample_config_value(rng, key),
                "note": f"Configuration value for {key} captured during investigation.",
            })

        per_case_evidence[case["id"]] = {
            "origin_component_id": target_component,
            "causal_signal_ids": causal_signal_ids,
            "distractor_signal_ids": distractor_signal_ids,
            "has_clear_telemetry_anomaly": has_clear_anomaly,
            "telemetry_reading_count": len(telemetry_rows),
            "signal_count": len(causal_signal_ids) + len(distractor_signal_ids),
            "config_snapshot_count": n_cfg,
            "external_dependency_causal": pattern["dependency_flavored"] and rc_name in _EXTERNAL_FLAVORED_ROOT_CAUSES,
        }

    return {
        "case_telemetry": case_telemetry,
        "case_signals": case_signals,
        "configuration_snapshots": configuration_snapshots,
        "per_case": per_case_evidence,
    }


def _confidence_band(sufficiency, difficulty):
    band = {"sufficient": "high", "partially_sufficient": "medium", "insufficient": "low"}[sufficiency]
    if difficulty == "dependency_root_cause" and band == "high":
        band = "medium"
    return band


def build_observable_and_ground_truth(cases, changes_result, evidence_result, incident_result):
    per_change = changes_result["per_case"]
    per_evidence = evidence_result["per_case"]

    change_links_by_case = {}
    for row in changes_result["case_change_links"]:
        change_links_by_case.setdefault(row["case_id"], []).append(row)

    incident_by_case = incident_result["case_relationship"]

    observable, ground_truth = [], []
    for case in cases:
        cid = case["id"]
        ev = per_evidence[cid]
        ch = per_change[cid]
        nearby_changes = change_links_by_case.get(cid, [])
        incident_info = incident_by_case.get(cid)

        has_causal_signal = bool(ev["causal_signal_ids"])
        has_causal_change = bool(ch["causal_change_id"])
        if not ev["has_clear_telemetry_anomaly"] and ev["signal_count"] <= 1 and not has_causal_change:
            sufficiency = "insufficient"
        elif has_causal_signal or has_causal_change or ev["has_clear_telemetry_anomaly"]:
            sufficiency = "sufficient"
        else:
            sufficiency = "partially_sufficient"

        observable.append({
            "case_id": cid,
            "has_telemetry": "true" if ev["telemetry_reading_count"] > 0 else "false",
            "telemetry_reading_count": ev["telemetry_reading_count"],
            "signal_count": ev["signal_count"],
            "nearby_change_count": len(nearby_changes),
            "config_snapshot_count": ev["config_snapshot_count"],
            "incident_window_overlap": "true" if incident_info else "false",
        })

        ground_truth.append({
            "case_id": cid,
            "causal_component_id": ev["origin_component_id"],
            "origin_component_id": ev["origin_component_id"],
            "causal_change_id": ch["causal_change_id"],
            "contributing_change_ids": ";".join(ch["contributing_change_ids"]),
            "irrelevant_change_ids": ";".join(ch["irrelevant_change_ids"]),
            "causal_signal_ids": ";".join(ev["causal_signal_ids"]),
            "distractor_signal_ids": ";".join(ev["distractor_signal_ids"]),
            "incident_id": incident_info["incident_id"] if incident_info else "",
            "incident_relationship": incident_info["relationship"] if incident_info else "",
            "external_dependency_causal": "true" if ev.get("external_dependency_causal") else "false",
            "evidence_sufficiency": sufficiency,
            "expected_confidence_band": _confidence_band(sufficiency, case["gt_difficulty_archetype"]),
        })

    return observable, ground_truth
